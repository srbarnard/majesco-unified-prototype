type TaskAttachmentSeed = {
  id: string
  name: string
  kind?: PolicyDocument['kind']
  description: string
  aiSummary: string
  tags?: string[]
  fileName?: string
}

function toFileName(name: string, kind: PolicyDocument['kind']) {
  const base = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '')
  if (kind === 'Form') return `${base}.pdf`
  if (kind === 'Package') return `${base}_package.pdf`
  if (base.includes('xlsx') || base.includes('schedule') || base.includes('payroll') || base.includes('worksheet')) {
    return `${base}.xlsx`
  }
  return `${base}.pdf`
}

function buildAttachment(seed: TaskAttachmentSeed): PolicyDocument {
  const kind = seed.kind ?? 'Document'
  return {
    id: seed.id,
    fileName: seed.fileName ?? toFileName(seed.name, kind),
    name: seed.name,
    kind,
    description: seed.description,
    aiSummary: seed.aiSummary,
    tags: seed.tags ?? ['Task attachment'],
    author: 'Task workspace',
    authorDetail: 'Attached from open task',
    date: '2026-06-25',
    relativeTime: '2d ago',
    activityLabel: 'Task',
    activityCount: 0,
  }
}

